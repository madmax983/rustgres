/// v2.28: identity columns (GENERATED {ALWAYS|BY DEFAULT} AS
/// IDENTITY) — sequence-backed generation, OVERRIDING, attidentity,
/// ALTER ADD/DROP/SET identity, partition sharing, PG error codes.
/// Ground truth: PG19 identity.sql/identity.out, parse_utilcmd.c,
/// tablecmds.c, sequence.c. Scope record: hidden_files/v228/scope.md.
use super::*;
use crate::sql::parse_statement;

fn engine() -> Engine {
    Engine::new()
}

fn run(eng: &mut Engine, sql: &str) -> Result<ExecResult, ExecError> {
    let stmt = parse_statement(sql).map_err(|e| exec_err(e.code, e.message))?;
    let snap = eng.take_snapshot();
    let mut writes = Vec::new();
    let mut ctx = StmtCtx {
        privs_suppressed: false,
        snap: &snap,
        own: 9,
        write_xid: 9,
        all_xids: vec![9],
        level: IsolationLevel::ReadCommitted,
        writes: &mut writes,
        session: 0,
        role: "postgres",
        read_only: false,
        default_toast_compression: crate::storage::ToastCompression::Pglz,
        notices: Vec::new(),
    };
    execute(eng, &mut ctx, &stmt)
}

fn ok(eng: &mut Engine, sql: &str) {
    run(eng, sql).unwrap_or_else(|e| panic!("{sql} -> {} {}", e.code, e.message));
}

fn err(eng: &mut Engine, sql: &str) -> ExecError {
    match run(eng, sql) {
        Ok(_) => panic!("{sql} -> expected error, got success"),
        Err(e) => e,
    }
}

fn rows_text(eng: &mut Engine, sql: &str) -> Vec<Vec<String>> {
    match run(eng, sql) {
        Ok(ExecResult::Select { rows, .. }) => rows
            .iter()
            .map(|r| r.iter().map(|v| v.to_text().unwrap_or_default()).collect())
            .collect(),
        other => panic!("expected Select for {sql} -> {other:?}"),
    }
}

#[test]
fn v228_create_insert_matrix() {
    let mut eng = engine();
    ok(
        &mut eng,
        "CREATE TABLE i1 (a int generated by default as identity, b text)",
    );
    ok(
        &mut eng,
        "CREATE TABLE i2 (a bigint generated always as identity, b text)",
    );
    ok(&mut eng, "INSERT INTO i1 DEFAULT VALUES");
    ok(&mut eng, "INSERT INTO i1 VALUES (10, 'x')");
    ok(
        &mut eng,
        "INSERT INTO i1 OVERRIDING USER VALUE VALUES (30, 'x')",
    );
    ok(&mut eng, "INSERT INTO i2 DEFAULT VALUES");
    assert_eq!(
        rows_text(&mut eng, "SELECT a FROM i1 ORDER BY a"),
        vec![vec!["1"], vec!["2"], vec!["10"]]
    );
    let e = err(&mut eng, "INSERT INTO i2 VALUES (10, 'x')");
    assert_eq!(e.code, "428C9");
    ok(
        &mut eng,
        "INSERT INTO i2 OVERRIDING SYSTEM VALUE VALUES (20, 'x')",
    );
    assert_eq!(
        rows_text(&mut eng, "SELECT a FROM i2 ORDER BY a"),
        vec![vec!["1"], vec!["20"]]
    );
}

#[test]
fn v228_create_error_codes() {
    let mut eng = engine();
    assert_eq!(
        err(
            &mut eng,
            "CREATE TABLE e1 (a text generated by default as identity)"
        )
        .code,
        "42P16"
    );
    assert_eq!(
        err(
            &mut eng,
            "CREATE TABLE e2 (a int default 5 generated by default as identity)"
        )
        .code,
        "42601"
    );
    assert_eq!(
        err(
            &mut eng,
            "CREATE TABLE e3 (a serial generated by default as identity)"
        )
        .code,
        "42601"
    );
    assert_eq!(
        err(
            &mut eng,
            "CREATE TABLE e4 (a int generated always as identity generated by default as identity)"
        )
        .code,
        "42601"
    );
    // PG19 allows multiple identity columns per table
    // (create_table.sgml: OVERRIDING applies statement-wide).
    ok(
        &mut eng,
        "CREATE TABLE e5 (a int generated always as identity, b int generated always as identity)",
    );
    ok(&mut eng, "INSERT INTO e5 DEFAULT VALUES");
    assert_eq!(
        rows_text(&mut eng, "SELECT a, b FROM e5"),
        vec![vec!["1", "1"]]
    );
    assert_eq!(
        err(
            &mut eng,
            "CREATE TABLE e6 (a int null generated always as identity)"
        )
        .code,
        "42601"
    );
}

#[test]
fn v228_attidentity_and_info_schema() {
    let mut eng = engine();
    ok(
        &mut eng,
        "CREATE TABLE i1 (a int generated always as identity, b int generated by default as identity, c int)",
    );
    assert_eq!(
        rows_text(
            &mut eng,
            "SELECT attname, attidentity FROM pg_attribute WHERE attname IN ('a','b','c') ORDER BY attname"
        ),
        vec![vec!["a", "a"], vec!["b", "d"], vec!["c", ""]]
    );
    assert_eq!(
        rows_text(
            &mut eng,
            "SELECT column_name, is_identity, identity_generation FROM information_schema.columns WHERE column_name IN ('a','b','c') ORDER BY column_name"
        ),
        vec![
            vec!["a", "YES", "ALWAYS"],
            vec!["b", "YES", "BY DEFAULT"],
            vec!["c", "NO", ""]
        ]
    );
    // Identity sequences hidden from information_schema.sequences.
    assert_eq!(
        rows_text(
            &mut eng,
            "SELECT sequence_name FROM information_schema.sequences WHERE sequence_name LIKE 'i1%'"
        ),
        Vec::<Vec<String>>::new()
    );
    assert_eq!(
        rows_text(&mut eng, "SELECT pg_get_serial_sequence('i1', 'a')"),
        vec![vec!["public.i1_a_seq"]]
    );
}

#[test]
fn v228_alter_add_drop_set_identity() {
    let mut eng = engine();
    ok(&mut eng, "CREATE TABLE t (a int, b text)");
    let e = err(
        &mut eng,
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY",
    );
    assert_eq!(e.code, "55000");
    ok(&mut eng, "ALTER TABLE t ALTER COLUMN a SET NOT NULL");
    ok(
        &mut eng,
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY",
    );
    let e = err(
        &mut eng,
        "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY",
    );
    assert_eq!(e.code, "55000");
    let e = err(&mut eng, "ALTER TABLE t ALTER COLUMN a DROP NOT NULL");
    assert_eq!(e.code, "55000");
    let e = err(&mut eng, "ALTER TABLE t ALTER COLUMN a SET DEFAULT 1");
    assert_eq!(e.code, "55000");
    ok(&mut eng, "INSERT INTO t DEFAULT VALUES");
    ok(
        &mut eng,
        "ALTER TABLE t ALTER COLUMN a SET GENERATED BY DEFAULT SET START WITH 100 RESTART",
    );
    ok(&mut eng, "INSERT INTO t DEFAULT VALUES");
    assert_eq!(
        rows_text(&mut eng, "SELECT a FROM t ORDER BY a"),
        vec![vec!["1"], vec!["100"]]
    );
    ok(&mut eng, "ALTER TABLE t ALTER COLUMN a DROP IDENTITY");
    let e = err(&mut eng, "ALTER TABLE t ALTER COLUMN a DROP IDENTITY");
    assert_eq!(e.code, "55000");
    ok(
        &mut eng,
        "ALTER TABLE t ALTER COLUMN a DROP IDENTITY IF EXISTS",
    );
    assert_eq!(
        rows_text(
            &mut eng,
            "SELECT sequence_name FROM information_schema.sequences WHERE sequence_name = 't_a_seq'"
        ),
        Vec::<Vec<String>>::new()
    );
}

#[test]
fn v228_add_column_and_partitions() {
    let mut eng = engine();
    ok(&mut eng, "CREATE TABLE t (a int)");
    ok(&mut eng, "INSERT INTO t VALUES (1), (2)");
    ok(
        &mut eng,
        "ALTER TABLE t ADD COLUMN b int GENERATED BY DEFAULT AS IDENTITY",
    );
    assert_eq!(
        rows_text(&mut eng, "SELECT b FROM t ORDER BY a"),
        vec![vec!["1"], vec!["2"]]
    );
    // Partitioned parent: identity shared across partitions.
    ok(
        &mut eng,
        "CREATE TABLE p (f1 date NOT NULL, f3 bigint generated always as identity) PARTITION BY RANGE (f1)",
    );
    ok(
        &mut eng,
        "CREATE TABLE p1 PARTITION OF p FOR VALUES FROM ('2016-07-01') TO ('2016-08-01')",
    );
    ok(&mut eng, "INSERT INTO p (f1) VALUES ('2016-07-02')");
    ok(&mut eng, "INSERT INTO p1 (f1) VALUES ('2016-07-03')");
    assert_eq!(
        rows_text(&mut eng, "SELECT f3 FROM p ORDER BY f3"),
        vec![vec!["1"], vec!["2"]]
    );
    // PARTITION OF element identity stays a 0A000 rejection.
    let e = err(
        &mut eng,
        "CREATE TABLE p2 PARTITION OF p (f3 WITH OPTIONS GENERATED ALWAYS AS IDENTITY) FOR VALUES FROM ('2016-08-01') TO ('2016-09-01')",
    );
    assert_eq!(e.code, "0A000");
    // DETACH strips identity + default.
    ok(&mut eng, "ALTER TABLE p DETACH PARTITION p1");
    assert_eq!(
        rows_text(
            &mut eng,
            "SELECT is_identity FROM information_schema.columns WHERE table_name = 'p1' AND column_name = 'f3'"
        ),
        vec![vec!["NO"]]
    );
}

